// The recorded output under testdata/own-package is Grype 0.121.0 (with --by-cve, writing SARIF and
// JSON) and Trivy 0.76.1 (fs --scanners vuln --format json --list-all-pkgs --show-suppressed
// --include-dev-deps --offline-scan), each run over the two trees below. The SARIF is as Grype wrote
// it. In the JSON the directory scanned is replaced by /checkout, and Grype's descriptor is cut to
// its name and version, as testdata/pom-scopes's is, since the rest is the machine's configuration.
//
// Neither tree depends on anything. Each finding is about the project's own package: telemetry, a
// member of a Cargo workspace named like a crate with a critical advisory, and webpack-json, a
// package-lock.json root named like a package GitHub lists as malware.
const (
	ownWorkspaceCargoToml = "[workspace]\nmembers = [\"app\", \"telemetry\"]\nresolver = \"2\"\n"
	ownWorkspaceCargoLock = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "telemetry",
]

[[package]]
name = "telemetry"
version = "0.1.0"
`
	ownSitePackageJSON = `{"name": "webpack-json", "version": "1.0.0", "private": true}`
	ownSiteLock        = `{
  "name": "webpack-json",
  "version": "1.0.0",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "webpack-json",
      "version": "1.0.0",
      "dependencies": {}
    }
  }
}
`
)

func ownPackageRead(t *testing.T, name string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join("testdata", "own-package", name)) // #nosec G304 -- under testdata
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// runOwnPackages scans two components, workspace and site, each on its own repository, with
// trivy-fs and grype-fs under the real sca control, each scanner replaying what it wrote for the
// repository it was given.
func runOwnPackages(t *testing.T, sca saga.ControllerSettings, components map[string]saga.ControllerSettings) engine.Result {
	t.Helper()
	dirs := map[string]string{
		"workspace": writeTree(t, map[string]string{
			"Cargo.toml": ownWorkspaceCargoToml, "Cargo.lock": ownWorkspaceCargoLock,
			"app/Cargo.toml":       "[package]\nname = \"app\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\ntelemetry = { path = \"../telemetry\" }\n",
			"app/src/main.rs":      "fn main() {}\n",
			"telemetry/Cargo.toml": "[package]\nname = \"telemetry\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
			"telemetry/src/lib.rs": "\n",
		}),
		"site": writeTree(t, map[string]string{"package.json": ownSitePackageJSON, "package-lock.json": ownSiteLock}),
	}
	repoOf := map[string]string{dirs["workspace"]: "workspace", dirs["site"]: "site"}
	checkout := func(_ context.Context, url, _ string, _ git.Scope) (git.Tree, func(), error) {
		return git.Tree{Dir: dirs[url]}, func() {}, nil
	}

	prior := grypeRunInDir
	t.Cleanup(func() { grypeRunInDir = prior })
	grypeRunInDir = func(_ context.Context, dir string, argv []string) ([]byte, error) {
		repo := repoOf[dir]
		fakeGrypeOutputs(t, argv, string(ownPackageRead(t, repo+".grype.json")))
		return ownPackageRead(t, repo+".grype.sarif"), nil
	}
	grype := NewGrypeFS().(repoScanner)
	grype.checkout, grype.prewarm, grype.cacheVersion, grype.dataState = checkout, nil, nil, nil

	trivy := NewTrivyFS().(repoScanner)
	trivy.checkout, trivy.prewarm, trivy.cacheVersion, trivy.dataState = checkout, nil, nil, nil
	trivy.runLogged = trivyFSRun(func(_ context.Context, dir string, _ []string) ([]byte, []byte, error) {
		return ownPackageRead(t, repoOf[dir]+".trivy.json"), nil, nil
	})

	reg := engine.NewRegistry()
	reg.RegisterController(controllers.NewSCA())
	reg.RegisterScanner(grype)
	reg.RegisterScanner(trivy)

	project := saga.ControllerSettings{"enabled": true, "grypeFs": map[string]any{"enabled": true}}
	for k, v := range sca {
		project[k] = v
	}
	model := saga.Model{Config: saga.Config{Controls: map[string]saga.ControllerSettings{"sca": project}}}
	for _, name := range []string{"workspace", "site"} {
		comp := saga.Component{Name: name, Repositories: []saga.Repository{{URL: name}}}
		if s, ok := components[name]; ok {
			comp.Controls = map[string]saga.ControllerSettings{"sca": s}
		}
		model.Components = append(model.Components, comp)
	}
	res, err := engine.New(reg).Run(context.Background(), model)
	if err != nil {
		t.Fatal(err)
	}
	return res
}

// ownFindings are a run's sca findings, each as "<component> <tool> <vulnerability> <package>",
// sorted, split into the ones counted and the ones set aside with the suppression each carries. A
// finding whose package is not marked own fails the test, since every finding these trees produce
// is about the project's own package.
func ownFindings(t *testing.T, res engine.Result) (counted []string, setAside map[string]sarif.Suppression) {
	t.Helper()
	setAside = map[string]sarif.Suppression{}
	for _, r := range res.Controls["sca"].Report.Results {
		if r.Package == nil {
			t.Fatalf("%s %s %s carries no package", r.Component, r.Tool, r.RuleID)
		}
		id := r.Component + " " + r.Tool + " " + r.VulnerabilityID() + " " + r.Package.Name
		if !r.Package.Own {
			t.Errorf("%s: not marked as the project's own package", id)
		}
		switch {
		case r.Suppressed():
			setAside[id] = *r.Suppression
		case !r.Correlated():
			counted = append(counted, id)
		}
	}
	slices.Sort(counted)
	return counted, setAside
}

var ownPackageFindings = []string{
	"site grype GHSA-69hx-wrc9-h5wq webpack-json",
	"workspace grype CVE-2021-29937 telemetry",
	"workspace trivy CVE-2021-29937 telemetry",
}

// With nothing written, every scanner's finding about a Cargo workspace member and about a
// package-lock.json's root stays in the report, marked own and suppressed by the setting, and none
// reaches the counts or the gate.
func TestOwnPackagesAreSuppressedByDefault(t *testing.T) {
	res := runOwnPackages(t, nil, nil)
	counted, setAside := ownFindings(t, res)
	if len(counted) > 0 {
		t.Errorf("counted %v, want none", counted)
	}
	for _, id := range ownPackageFindings {
		s, ok := setAside[id]
		if !ok {
			t.Errorf("%s not suppressed", id)
			continue
		}
		if s.Origin != sarif.OriginSetting || s.Justification != sarif.JustificationOwnPackage ||
			s.Source != "config.controls.sca.ownPackages" {
			t.Errorf("%s suppression %+v, want the setting config.controls.sca.ownPackages with reason %q",
				id, s, sarif.JustificationOwnPackage)
		}
	}
	if len(setAside) != len(ownPackageFindings) {
		t.Errorf("set aside %d findings, want %d", len(setAside), len(ownPackageFindings))
	}
	if res.OwnPackages != len(ownPackageFindings) {
		t.Errorf("OwnPackages = %d, want %d", res.OwnPackages, len(ownPackageFindings))
	}
	if sum := res.Controls["sca"].Summary; sum != (plugin.Summary{}) {
		t.Errorf("sca summary %+v, want nothing counted", sum)
	}
	if res.Suppressed != 0 {
		t.Errorf("Suppressed = %d, want 0: config.exclude set nothing aside", res.Suppressed)
	}
}

// ownPackages: report counts them, marked own. Grype gives a workspace member no package URL and
// Trivy gives it pkg:cargo/telemetry@0.1.0, and the two copies still meet on the URL's type, name and
// version: the one flaw counts once, under Trivy's copy, and Grype's is listed beside it.
func TestOwnPackagesReportCountsThem(t *testing.T) {
	res := runOwnPackages(t, saga.ControllerSettings{"ownPackages": "report"}, nil)
	counted, setAside := ownFindings(t, res)
	want := []string{"site grype GHSA-69hx-wrc9-h5wq webpack-json", "workspace trivy CVE-2021-29937 telemetry"}
	if !slices.Equal(counted, want) {
		t.Errorf("counted %v, want %v", counted, want)
	}
	if len(setAside) > 0 {
		t.Errorf("set aside %v, want none", setAside)
	}
	for _, r := range res.Controls["sca"].Report.Results {
		if r.Tool == "grype" && r.Package.Name == "telemetry" && (!r.Correlated() || r.Package.PURL != "") {
			t.Errorf("Grype's telemetry: correlated %v, package URL %q; want correlated, with no URL", r.Correlated(), r.Package.PURL)
		}
	}
}

// A component's ownPackages replaces the project's, and the suppression names the component's key.
func TestAComponentsOwnPackagesReplacesTheProjects(t *testing.T) {
	res := runOwnPackages(t, saga.ControllerSettings{"ownPackages": "report"},
		map[string]saga.ControllerSettings{"site": {"ownPackages": "suppress"}})
	counted, setAside := ownFindings(t, res)
	if want := ownPackageFindings[2:]; !slices.Equal(counted, want) {
		t.Errorf("counted %v, want %v", counted, want)
	}
	s, ok := setAside[ownPackageFindings[0]]
	if !ok || len(setAside) != 1 {
		t.Fatalf("set aside %v, want only %s", setAside, ownPackageFindings[0])
	}
	if want := `components["site"].controls.sca.ownPackages`; s.Source != want {
		t.Errorf("suppression source %q, want %q", s.Source, want)
	}
}

// Trivy's relationship marks its own finding, whatever file it is in: a workspace member or a root
// is the project, and a direct or indirect dependency is not.
func TestTrivyMarksRootAndWorkspacePackagesOwn(t *testing.T) {
	rep, err := parseTrivyVulns(ownPackageRead(t, "workspace.trivy.json"), "", plugin.Config{})
	if err != nil {
		t.Fatal(err)
	}
	if len(rep.Results) != 1 || !rep.Results[0].Package.Own {
		t.Fatalf("results %+v, want telemetry marked own", rep.Results)
	}
	const doc = `{"Results":[{"Target":"go.mod","Class":"lang-pkgs","Type":"gomod",
 "Packages":[{"Name":"example.com/app","Identifier":{"UID":"a"},"Relationship":"root"},
  {"Name":"golang.org/x/text","Identifier":{"UID":"b"},"Relationship":"direct"}],
 "Vulnerabilities":[
  {"VulnerabilityID":"CVE-1","PkgName":"example.com/app","PkgIdentifier":{"UID":"a"},"Severity":"HIGH"},
  {"VulnerabilityID":"CVE-2","PkgName":"golang.org/x/text","PkgIdentifier":{"UID":"b"},"Severity":"HIGH"}],
 "ExperimentalModifiedFindings":[{"Type":"vulnerability","Status":"ignored","Source":".trivyignore",
  "Finding":{"VulnerabilityID":"CVE-3","PkgName":"example.com/app","PkgIdentifier":{"UID":"a"}}}]}]}`
	rep, err = parseTrivyVulns([]byte(doc), "", plugin.Config{})
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]bool{"CVE-1": true, "CVE-2": false, "CVE-3": true}
	for _, r := range rep.Results {
		if r.Package.Own != want[r.RuleID] {
			t.Errorf("%s: own %v, want %v", r.RuleID, r.Package.Own, want[r.RuleID])
		}
	}
	if len(rep.Results) != len(want) {
		t.Errorf("%d results, want %d", len(rep.Results), len(want))
	}
}

// A finding is marked only where its package is one the file at its location records as the
// project's own; anything else keeps what its scanner said, and the scanner's value is copied.
func TestMarkOwnPackages(t *testing.T) {
	dir := writeTree(t, map[string]string{
		"Cargo.lock":                       ownWorkspaceCargoLock,
		"site/package-lock.json":           `{"lockfileVersion": 3, "packages": {"": {"dependencies": {}}}}`,
		"site/package.json":                ownSitePackageJSON,
		"node_modules/x/package-lock.json": ownSiteLock,
		"plugins/ffmpeg/pubspec.yaml":      "name: ffmpeg\nversion: 0.0.1\npublish_to: none\n",
		"plugins/http/pubspec.yaml":        "name: http\nversion: 1.0.0\n",
		"ios/Podfile.lock":                 "PODS:\n  - Flutter (1.0.0)\nEXTERNAL SOURCES:\n  Flutter:\n    :path: Flutter\n",
		"requirements.txt":                 "telemetry==0.1.0\n",
	})
	at := func(uri, name, version string) sarif.Result {
		r := sarif.Result{RuleID: "r", Package: &sarif.Package{Name: name, Version: version}}
		r.Location.URI = uri
		return r
	}
	results := []sarif.Result{
		at("Cargo.lock", "telemetry", "0.1.0"),
		at("Cargo.lock", "telemetry", "0.2.0"),
		at("Cargo.lock", "serde", "1.0.0"),
		at("site/package-lock.json", "webpack-json", "1.0.0"),
		at("node_modules/x/package-lock.json", "webpack-json", "1.0.0"),
		at("plugins/ffmpeg/pubspec.yaml", "ffmpeg", "0.0.1"),
		at("plugins/http/pubspec.yaml", "http", "1.0.0"),
		at("ios/Podfile.lock", "Flutter", "1.0.0"),
		at("ios/Podfile.lock", "Firebase", "10.0.0"),
		at("requirements.txt", "telemetry", "0.1.0"),
		at("missing/Cargo.lock", "telemetry", "0.1.0"),
		at("../Cargo.lock", "telemetry", "0.1.0"),
		{RuleID: "r", Location: sarif.Location{URI: "Cargo.lock"}},
		{RuleID: "r", Location: sarif.Location{URI: "requirements.txt"}, Package: &sarif.Package{Name: "x", Own: true}},
	}
	shared := results[0].Package
	markOwnPackages(results, dir)
	want := []bool{true, false, false, true, false, true, false, true, false, false, false, false, false, true}
	for i, w := range want {
		p := results[i].Package
		if p == nil {
			continue
		}
		if p.Own != w {
			t.Errorf("result %d, %s %s at %s: own %v, want %v", i, p.Name, p.Version, results[i].Location.URI, p.Own, w)
		}
	}
	if shared.Own {
		t.Error("the scanner's package value was changed in place rather than copied")
	}
}
