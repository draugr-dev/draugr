#!/usr/bin/env python3
"""Write a composite action that runs action.yml's cosign install steps as they stand.

Usage: cosign-install-steps.py <action.yml> <out dir> [<step id> ...]

It copies the steps from the one with id cosign-first through the one with id cosign-check, and
points each step id named after the out dir at a cosign release that does not exist, so that
attempt fails. CI runs the result to show that a failed first attempt is followed by a second,
and that the action fails when both fail. The steps are read from action.yml each time, so the
check follows any later edit to them. The composite's outputs give each attempt's outcome.
"""
import pathlib
import re
import sys

# A version the installer accepts, so the attempt fails on the download, not on the version check.
MISSING = "v9.9.9"
STEP = "    - "


def main():
    action, out, *broken = sys.argv[1:]
    lines = pathlib.Path(action).read_text().splitlines()
    starts = [i for i, line in enumerate(lines) if line.startswith(STEP)]
    bounds = list(zip(starts, starts[1:] + [len(lines)]))

    def step(step_id):
        for start, end in bounds:
            if "      id: " + step_id in lines[start:end]:
                return start, end
        sys.exit("%s has no step with id %s" % (action, step_id))

    first, _ = step("cosign-first")
    _, end = step("cosign-check")
    # The comment above the step after the check belongs to that step.
    while lines[end - 1].strip() == "" or lines[end - 1].strip().startswith("#"):
        end -= 1

    body, current, done = [], None, set()
    for line in lines[first:end]:
        if line.startswith(STEP):
            current = None
        if line.startswith("      id: "):
            current = line.split(":", 1)[1].strip()
        if current in broken and line.startswith("      with:"):
            sys.exit("step %s already has inputs; this script would need to merge them" % current)
        body.append(line)
        if current in broken and line.startswith("      uses: sigstore/cosign-installer@"):
            body += ["      with:", "        cosign-release: " + MISSING]
            done.add(current)
    if done != set(broken):
        sys.exit("no cosign installer step with id %s" % ", ".join(sorted(set(broken) - done)))

    used = set(re.findall(r"inputs\.([A-Za-z0-9_-]+)", "\n".join(body)))
    if used - {"verify"}:
        sys.exit("the steps read inputs this script does not declare: %s" % ", ".join(sorted(used)))

    head = [
        "name: cosign install steps of action.yml",
        "description: Generated by scripts/cosign-install-steps.py for CI; not committed.",
        "inputs:",
        "  verify:",
        "    description: As the action's input of the same name.",
        "    default: 'true'",
        "outputs:",
        "  first:",
        "    description: The first attempt's outcome.",
        "    value: ${{ steps.cosign-first.outcome }}",
        "  second:",
        "    description: The second attempt's outcome, empty when it did not run.",
        "    value: ${{ steps.cosign-second.outcome }}",
        "runs:",
        "  using: composite",
        "  steps:",
    ]
    path = pathlib.Path(out)
    path.mkdir(parents=True, exist_ok=True)
    (path / "action.yml").write_text("\n".join(head + body) + "\n")
    print("wrote %s: steps %d to %d of %s, broken: %s" % (
        path / "action.yml", first + 1, end, action, ", ".join(broken) or "none"))


if __name__ == "__main__":
    main()
